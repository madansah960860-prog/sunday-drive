          <div class="section-head">
            <span class="tab">The story</span>
            <h2 id="story-title">It began with a timer</h2>
          </div>
          <p>One of us inherited a wind-up kitchen timer that had been ticking since the Eisenhower
             administration and could be heard from the garage. When it finally gave out, replacing it
             turned out to be surprisingly hard — everything on the shelf beeped, needed a battery, or
             was a novelty that fell apart in a month.</p>
          <p>Fifteen products later, that is still the whole editorial line: things that were designed
             before batteries were assumed, made new, sold honestly. We are not selling nostalgia for
             a decade we mostly did not live in. We are selling a bell you can hear from the garage.</p>
